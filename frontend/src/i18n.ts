const DICT: Record<string, { gu: string; hi: string }> = {};
for (const [en, gu, hi] of [...ROWS, ...MORE_ROWS]) DICT[en] = { gu, hi };

/** Translates a fixed English string. Unknown strings stay in English. */
export const t = (s: string): string => (lang === 'en' ? s : DICT[s]?.[lang] ?? s);

/** Like t() but fills {placeholders}. */
export const tf = (s: string, vars: Record<string, string | number>): string =>
  t(s).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));

/** Fills {postal} (PIN code / ZIP code, translated) and {n} (its length) in a translated sentence. */
export const tp = (s: string): string => t(s).replace(/\{postal\}/g, t(cfg.postalLabel)).replace(/\{n\}/g, String(cfg.postalLength));

/** Translates well-known catalog texts (service names and descriptions) anywhere in data that came from the server. */
export function localizeData<T>(x: T): T {
  if (lang === 'en') return x;
  const walk = (v: unknown): unknown => {
    if (typeof v === 'string') return DICT[v] ? DICT[v][lang] : v;
    if (Array.isArray(v)) return v.map(walk);
    if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, val]) => [k, walk(val)]));
    return v;
  };
  return walk(x) as T;
}

/** Chat updates written by the server follow fixed patterns; translate the common ones. */
export function tMessage(text: string): string {
  if (lang === 'en') return text;
  let m = /^Status: (.+) \((.+)\)$/.exec(text);
  if (m) return `${t('Status')}: ${t(m[1])} (${m[2]})`;
  m = /^Appointment requested for (\S+) at (\S+)\.$/.exec(text);
  if (m) return tf('Appointment requested for {date} at {time}.', { date: m[1], time: m[2] });
  return t(text);
}
